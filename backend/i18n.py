"""Server-side translations: error messages, emails, export labels and the starter food catalog.
Source texts are in English. To add a language: a dictionary in MESSAGES, its LABELS, EMAILS and
STARTER_FOODS, and the code in LANGUAGES."""
import re

from flask import g, has_request_context, request

LANGUAGES = ['it', 'en', 'es', 'pt', 'fr', 'de']
DEFAULT = 'en'


def normalize(value):
    v = str(value or '').lower()[:2]
    return v if v in LANGUAGES else None


def language():
    """Request language: user profile > X-Language header (from the frontend) > Accept-Language > default."""
    if not has_request_context():
        return DEFAULT
    user = getattr(g, 'user', None)
    if user and normalize(user.get('language')):
        return user['language']
    return (normalize(request.headers.get('X-Language'))
            or request.accept_languages.best_match(LANGUAGES)
            or DEFAULT)


